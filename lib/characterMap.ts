const KEY_BY_NAME: Record<string, CharacterKey> = Object.fromEntries(
  Object.entries(CHARACTER_NAMES).map(([key, name]) => [name, key]),
);

/** 캐릭터 이름 → 파일 키. */
export function characterKeyByName(name: string): CharacterKey | null {
  return KEY_BY_NAME[name] ?? null;
}

/** 학교명(정확히 일치) → 배정된 캐릭터 파일 키. 목록에 없는 학교면 null. */
export function characterKeyForSchool(school: string): CharacterKey | null {
  const name = SCHOOL_CHARACTERS[school.trim()];
  return name ? (KEY_BY_NAME[name] ?? null) : null;
}

/** 파일 키 → 캐릭터 이름 (픽커 라벨용). */
export function characterName(key: CharacterKey | null): string | null {
  return key ? (CHARACTER_NAMES[key] ?? null) : null;
}
